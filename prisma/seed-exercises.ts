/**
 * Standaard oefeningen-database voor Movement Based Therapy Amsterdam.
 * Evidence-based muscleLoads op basis van peer-reviewed EMG-studies (2000-2025).
 *
 * Conversie % MVIC → 1-5 schaal:
 *   0-20%  = 1 (lichte activatie)
 *   21-40% = 2 (matig-licht)
 *   41-60% = 3 (matig)
 *   61-80% = 4 (hoog)
 *   81%+   = 5 (zeer hoog)
 *
 * Zie emg_onderste_extremiteit.md en emg_bovenste_core.md voor bronvermelding.
 * Progressie/regressie wordt in seed.ts gekoppeld via exercise-progressions.ts.
 */

type SeedExtraParam = {
  id: string
  label: string
  type: 'number' | 'text' | 'select' | 'slider'
  value: string | number
  unit?: string
  options?: string[]
  min?: number
  max?: number
}

type SeedExercise = {
  name: string
  description: string
  category: 'STRENGTH' | 'MOBILITY' | 'PLYOMETRICS' | 'CARDIO' | 'STABILITY'
  bodyRegion: string[]
  difficulty: 'BEGINNER' | 'INTERMEDIATE' | 'ADVANCED'
  loadType: 'BODYWEIGHT' | 'WEIGHTED' | 'MACHINE' | 'BAND'
  isUnilateral: boolean
  movementPattern: string | null
  tags: string[]
  instructions: string[]
  muscleLoads: Record<string, number>
  /** Primaire tracking-unit ('reps' is default — alleen overriden voor isometrische oefeningen). */
  defaultRepUnit?: 'reps' | 'sec' | 'min'
  /** Extra parameters die standaard verschijnen wanneer oefening in een programma komt (bv. Afstand voor sleds/carries). */
  defaultExtraParams?: SeedExtraParam[]
}

